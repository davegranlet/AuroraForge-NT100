'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const REPO_ROOT = path.resolve(__dirname, '../..');
const ROOT = path.resolve(process.argv[2] || REPO_ROOT);
const OUT_DIR = path.resolve(process.argv[3] || path.join(ROOT, '.local', 'repo-knowledge'));
const HASH_MODE = process.env.AURORA_AUDIT_HASH === '1';
const SKIP_DIRS = new Set(['.git', '.local', '.tools', 'node_modules', 'third_party']);

const TEXT_EXT = new Set([
  '.txt', '.md', '.json', '.jsonl', '.js', '.ts', '.tsx', '.jsx', '.c', '.cpp', '.h', '.hpp', '.cs', '.py', '.ps1', '.bat', '.cmd',
  '.xml', '.config', '.ini', '.csv', '.tsv', '.log', '.yml', '.yaml', '.sln', '.vcxproj', '.props', '.targets', '.csproj', '.html', '.css'
]);

const SOURCE_EXT = new Set(['.js', '.ts', '.tsx', '.jsx', '.c', '.cpp', '.h', '.hpp', '.cs', '.py', '.ps1', '.bat', '.cmd', '.sln', '.csproj', '.vcxproj']);
const GAME_EXT = new Set(['.cak', '.ftrib', '.acts', '.evd', '.clips', '.clip', '.adefs', '.jsfb', '.yanm20', '.anims', '.shdc', '.bpe', '.zlib', '.dds', '.tex', '.hkt', '.mprms', '.mtls', '.mcd', '.sdb', '.bk2', '.0fop']);
const BUILD_EXT = new Set(['.exe', '.dll', '.pdb', '.obj', '.o', '.ilk', '.lib', '.exp']);
const ARCHIVE_EXT = new Set(['.zip', '.rar', '.7z', '.gz', '.tar']);

function rel(p) { return path.relative(ROOT, p).replace(/\\/g, '/'); }
function lowerRel(p) { return rel(p).toLowerCase(); }
function ensureDir(p) { fs.mkdirSync(p, { recursive: true }); }
function isUnder(child, parent) {
  const r = path.relative(parent, child);
  return r === '' || (!!r && !r.startsWith('..') && !path.isAbsolute(r));
}

function classify(filePath, st) {
  const base = path.basename(filePath);
  const name = base.toLowerCase();
  const ext = path.extname(filePath).toLowerCase();
  const r = lowerRel(filePath);
  const tags = [];
  let category = 'unknown';
  let purpose = 'Unclassified file; metadata captured for lookup.';

  if (TEXT_EXT.has(ext)) tags.push('text');
  if (SOURCE_EXT.has(ext)) tags.push('source');
  if (GAME_EXT.has(ext)) tags.push('game-asset');
  if (BUILD_EXT.has(ext)) tags.push('build-artifact');
  if (ARCHIVE_EXT.has(ext)) tags.push('archive');
  if (r.includes('/backup') || r.includes('backup') || r.includes('/retired') || r.includes('checkpoint')) tags.push('backup-or-checkpoint');
  if (r.includes('/ghidra') || r.includes('decompiled') || r.includes('reverse')) tags.push('reverse-engineering');
  if (r.includes('/analysis') || r.includes('/probe') || r.includes('/audit') || r.includes('/research')) tags.push('research');
  if (r.includes('/_work/')) tags.push('workbench');
  if (r.includes('/node_modules/') || r.includes('/.git/')) tags.push('dependency-or-vcs-internal');

  if (SOURCE_EXT.has(ext)) {
    category = 'source-code';
    purpose = 'Source/tooling code used to build, inspect, convert, validate, or package Aurora Forge work.';
  } else if (GAME_EXT.has(ext)) {
    category = 'game-asset-or-container';
    purpose = 'Game asset/container/reference artifact used for extraction, conversion, registration, packaging, or validation.';
  } else if (BUILD_EXT.has(ext)) {
    category = 'executable-or-build-output';
    purpose = 'Compiled executable/library/object generated by a build or kept as a runnable/backup artifact.';
  } else if (ext === '.json' || ext === '.jsonl') {
    category = 'data-index-or-report';
    purpose = 'Structured data, inventory, report, package metadata, or generated audit information.';
  } else if (ext === '.md' || ext === '.txt' || ext === '.log') {
    category = 'documentation-or-log';
    purpose = 'Human-readable documentation, handoff, status ledger, catalog, or diagnostic log.';
  } else if (ext === '.csv' || ext === '.tsv') {
    category = 'tabular-inventory';
    purpose = 'Tabular inventory/baseline/catalog data used for file comparison or path lookup.';
  } else if (ARCHIVE_EXT.has(ext)) {
    category = 'archive';
    purpose = 'Compressed archive or packaged payload retained for release, transfer, or reference.';
  } else if (st.size === 0) {
    category = 'empty-file';
    purpose = 'Zero-byte placeholder or failed/interrupted generated artifact.';
  }

  if (name.includes('convert') || r.includes('converter')) tags.push('converter');
  if (name.includes('loader') || name === 'dinput8.dll' || ext === '.ftrib') tags.push('loader');
  if (name.includes('scan') || name.includes('probe') || name.includes('inspect') || name.includes('audit')) tags.push('analysis-tool');
  if (name.includes('build') || name.includes('bake') || name.includes('package')) tags.push('packaging');
  if (name.includes('victory') || r.includes('/victory')) tags.push('victory-animation');
  if (name.includes('entrance') || r.includes('/entrance') || r.includes('/entr')) tags.push('entrance-animation');
  if (name.includes('6100') || r.includes('6100')) tags.push('test-id-6100');
  if (name.includes('6185') || r.includes('6185')) tags.push('test-id-6185');
  if (name.includes('2k19') || r.includes('2k19')) tags.push('wwe2k19');
  if (name.includes('2k20') || r.includes('2k20')) tags.push('wwe2k20');
  if (name.includes('2k22') || r.includes('2k22')) tags.push('wwe2k22');
  if (name.includes('2k23') || r.includes('2k23')) tags.push('wwe2k23');
  if (name.includes('2k25') || r.includes('2k25') || r.includes('25')) tags.push('wwe2k25');
  if (name.includes('2k26') || r.includes('2k26') || r.includes('26')) tags.push('wwe2k26');

  return { category, purpose, tags: [...new Set(tags)].sort() };
}

function inferProject(relPath, repoName, tags) {
  const r = relPath.toLowerCase();
  const projects = [];
  function add(x) { if (!projects.includes(x)) projects.push(x); }
  if (repoName) add(repoName);
  if (r.includes('wwe2k19-to-2k26') || r.includes('2k19-to-2k26') || r.includes('entrance-prototype')) add('WWE2K19-to-2K26-Entrance-Prototype');
  if (r.includes('2k19-to-2k20') || r.includes('tonight-2k19-to-2k20')) add('Aurora-Forge-2K19-to-2K20-Converter');
  if (r.includes('secure-datactrllink')) add('Secure-DataCtrlLink');
  if (r.includes('cak-mod-loader') || tags.includes('loader')) add('Aurora-Forge-CAK-Mod-Loader');
  if (r.includes('cak-foundry') || r.includes('ftrib') || r.includes('bake')) add('Aurora-CAK-Foundry/FTribTool');
  if (r.includes('patreon')) add('Aurora-Forge-Patreon-Verifier');
  if (r.includes('clips') || r.includes('adefs') || r.includes('yanm') || r.includes('tbuf') || r.includes('animation')) add('Animation Converter Research');
  return projects;
}

function quickTextSummary(filePath, maxBytes) {
  try {
    const b = fs.readFileSync(filePath, { encoding: 'utf8', flag: 'r' }).slice(0, maxBytes);
    const lines = b.split(/\r?\n/).map(x => x.trim()).filter(Boolean);
    const interesting = [];
    for (const line of lines.slice(0, 80)) {
      if (/^(#|\/\/|\/\*|\*|function |class |const |let |var |module\.exports|exports\.|import |export |using |namespace |public |private |def |Describe|##)/.test(line)) {
        interesting.push(line.slice(0, 240));
      }
      if (interesting.length >= 8) break;
    }
    return { sample: interesting, lineCountSampled: lines.length };
  } catch (err) {
    return { sample: [], textReadError: err.message };
  }
}

function hashSmall(filePath, st) {
  if (!HASH_MODE) return null;
  if (st.size > 64 * 1024 * 1024) return null;
  try {
    const h = crypto.createHash('sha256');
    h.update(fs.readFileSync(filePath));
    return h.digest('hex').toUpperCase();
  } catch { return null; }
}

function walk(root, onEntry) {
  const stack = [root];
  while (stack.length) {
    const current = stack.pop();
    let st;
    try { st = fs.lstatSync(current); } catch (err) { onEntry(current, null, err); continue; }
    if (st.isDirectory()) {
      if (SKIP_DIRS.has(path.basename(current).toLowerCase())) continue;
    }
    onEntry(current, st, null);
    if (st.isDirectory()) {
      let kids;
      try { kids = fs.readdirSync(current); } catch { continue; }
      for (let i = kids.length - 1; i >= 0; i--) stack.push(path.join(current, kids[i]));
    }
  }
}

function main() {
  if (path.normalize(ROOT).toLowerCase() !== path.normalize(REPO_ROOT).toLowerCase()) {
    throw new Error(`Refusing to audit outside the canonical repository: ${ROOT}`);
  }
  if (!isUnder(OUT_DIR, path.join(ROOT, '.local'))) {
    throw new Error(`Audit outputs must stay under ${path.join(ROOT, '.local')}: ${OUT_DIR}`);
  }
  ensureDir(OUT_DIR);
  const filesPath = path.join(OUT_DIR, 'aurora-file-audit.jsonl');
  const summaryPath = path.join(OUT_DIR, 'aurora-file-audit-summary.json');
  const indexPath = path.join(OUT_DIR, 'aurora-file-audit-index.json');
  const out = fs.createWriteStream(filesPath, { encoding: 'utf8' });

  const startedAt = new Date().toISOString();
  const repos = [];
  const errors = [];
  const extCounts = new Map();
  const categoryCounts = new Map();
  let dirs = 0;
  let files = 0;
  let bytes = 0n;

  // First pass records repo roots and total counts. Hashing is off by default so
  // this can cover the whole workspace quickly; rerun with AURORA_AUDIT_HASH=1
  // only when cryptographic duplicate proof is needed.
  walk(ROOT, (p, st, err) => {
    if (err) { errors.push({ path: rel(p), error: err.message }); return; }
    if (st.isDirectory()) {
      dirs++;
      if (fs.existsSync(path.join(p, '.git'))) {
        repos.push({ name: path.basename(p), path: p, relPath: rel(p) });
      }
      return;
    }
    if (!st.isFile() && !st.isSymbolicLink()) return;
    files++;
    bytes += BigInt(st.size || 0);
    const ext = path.extname(p).toLowerCase() || '<none>';
    extCounts.set(ext, (extCounts.get(ext) || 0) + 1);
  });
  repos.sort((a, b) => b.path.length - a.path.length);

  const byName = new Map();
  const byRel = new Map();
  const sourceGroups = new Map();
  const records = [];
  let processed = 0;

  walk(ROOT, (p, st, err) => {
    if (err || !st || (!st.isFile() && !st.isSymbolicLink())) return;
    const repo = repos.find(x => isUnder(p, x.path));
    const ext = path.extname(p).toLowerCase();
    const base = path.basename(p);
    const rp = rel(p);
    const cls = classify(p, st);
    const projects = inferProject(rp, repo && repo.name, cls.tags);
    const text = TEXT_EXT.has(ext) && st.size <= 256 * 1024 ? quickTextSummary(p, 16 * 1024) : undefined;
    const sha256 = hashSmall(p, st);
    const repoRel = repo ? path.relative(repo.path, p).replace(/\\/g, '/') : null;
    const sourceGroupKey = SOURCE_EXT.has(ext) ? `${base.toLowerCase()}|${repoRel ? repoRel.toLowerCase() : rp.toLowerCase()}` : null;
    const rec = {
      path: p,
      relPath: rp,
      name: base,
      ext: ext || '<none>',
      size: st.size,
      mtime: st.mtime.toISOString(),
      ctime: st.ctime.toISOString(),
      sha256,
      category: cls.category,
      purpose: cls.purpose,
      textSummary: text,
      repo: repo ? { name: repo.name, relPath: repo.relPath, repoRelativePath: repoRel } : null,
      relatedProjects: projects,
      tags: cls.tags,
      relatedFiles: [],
      latestCodeVersion: false,
      latestCodeVersionReason: null,
    };
    processed++;
    categoryCounts.set(rec.category, (categoryCounts.get(rec.category) || 0) + 1);
    records.push(rec);
    if (!byName.has(base.toLowerCase())) byName.set(base.toLowerCase(), []);
    byName.get(base.toLowerCase()).push(records.length - 1);
    byRel.set(rp.toLowerCase(), records.length - 1);
    if (sourceGroupKey) {
      if (!sourceGroups.has(sourceGroupKey)) sourceGroups.set(sourceGroupKey, []);
      sourceGroups.get(sourceGroupKey).push(records.length - 1);
    }
  });

  for (const [name, idxs] of byName) {
    if (idxs.length < 2) continue;
    const related = idxs.map(i => records[i].relPath);
    for (const i of idxs) records[i].relatedFiles = related.filter(x => x !== records[i].relPath).slice(0, 200);
  }

  for (const [key, idxs] of sourceGroups) {
    if (!idxs.length) continue;
    let best = idxs[0];
    for (const i of idxs) {
      if (new Date(records[i].mtime) > new Date(records[best].mtime)) best = i;
    }
    records[best].latestCodeVersion = true;
    records[best].latestCodeVersionReason = `Newest modified source copy in group ${key}; ${idxs.length} related source copy/copies.`;
  }

  for (const rec of records) out.write(JSON.stringify(rec) + '\n');
  out.end();

  const index = {
    schema: 'aurora-forge-knowledge-index/v1',
    generatedAt: new Date().toISOString(),
    root: ROOT,
    filesJsonl: filesPath,
    lookup: {
      byName: Object.fromEntries([...byName.entries()].map(([k, idxs]) => [k, idxs.map(i => records[i].relPath).slice(0, 500)])),
      byRelPath: Object.fromEntries([...byRel.entries()].map(([k, i]) => [k, records[i].relPath])),
    },
  };
  fs.writeFileSync(indexPath, JSON.stringify(index, null, 2));

  const summary = {
    schema: 'aurora-forge-file-audit-summary/v1',
    generatedAt: new Date().toISOString(),
    startedAt,
    root: ROOT,
    outputs: { filesJsonl: filesPath, summaryJson: summaryPath, indexJson: indexPath },
    counts: { files, directories: dirs, bytes: bytes.toString(), repos: repos.length, errors: errors.length },
    repos: repos.slice().reverse(),
    extCounts: Object.fromEntries([...extCounts.entries()].sort((a, b) => b[1] - a[1])),
    categoryCounts: Object.fromEntries([...categoryCounts.entries()].sort((a, b) => b[1] - a[1])),
    notes: [
      'Every regular file under the canonical repository is represented, except .git, .local, .tools, node_modules, and third_party directories.',
      'Purpose fields are deterministic heuristics from path, extension, tags, and small text samples; binary semantics require later specialist decoding.',
      'latestCodeVersion marks the newest modified source copy within same-name/repo-relative source groups, not a git-approved release claim.',
    ],
    errors,
  };
  fs.writeFileSync(summaryPath, JSON.stringify(summary, null, 2));
  console.log(JSON.stringify(summary, null, 2));
}

main();
