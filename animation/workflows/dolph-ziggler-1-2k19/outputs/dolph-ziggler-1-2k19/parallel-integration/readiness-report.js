'use strict';
// readiness-report.js - assemble PROTOTYPE-READINESS.md for one immutable build.
// Reads build-report.json / verification.json / merge-report.json / build-intent.json
// and the live installed-snapshot diff embedded in verification.json.
// usage: node readiness-report.js <buildDir>
const fs = require('fs');
const path = require('path');
const L = require('./lib/integration.js');

const buildRoot = path.resolve(process.argv[2] || '');
if (!buildRoot || !fs.existsSync(buildRoot)) { console.error('usage: node readiness-report.js <buildDir>'); process.exit(2); }
const build = L.readJson(path.join(buildRoot, 'build-report.json'));
const verify = L.readJson(path.join(buildRoot, 'verification.json'));
const merge = L.readJson(path.join(buildRoot, 'merge-report.json'));
const intent = L.readJson(path.join(buildRoot, 'build-intent.json'));
const manifest = L.readJson(path.join(__dirname, 'components.json'));

const lines = [];
const put = (line) => lines.push(line);
const local = (iso) => new Date(iso).toLocaleString('en-US', { timeZone: 'America/New_York' });

put('# Prototype readiness - 14002/test557 integration build ' + build.buildId);
put('');
put('Generated ' + local(new Date().toISOString()) + ' (America/New_York) by the parallel-integration lane. Offline only:');
put('no install, no active-slot or bake-tree write, no game launch, no commit/push. Codex reviews and authorizes integration.');
put('');
put('## Artifact');
put('');
put('| Item | Value |');
put('|---|---|');
put('| CAK (do not rename) | `' + build.cak + '` |');
put('| SHA256 | `' + build.cakSha256 + '` |');
put('| Bytes | ' + build.cakBytes + ' |');
put('| Archive key | `' + build.archiveKey + '` (basename-derived; renaming changes the key) |');
put('| Members | ' + build.members + ' (37 payloads + generated 16-byte `_textures.tdb`) |');
put('| Manifest hash | `' + build.manifestHash + '` |');
put('| Verification | ' + verify.passed + '/' + verify.passed + ' checks pass' + (verify.failed ? ' (FAILED: ' + verify.failed + ')' : '') + ' |');
put('');
put('## Component provenance (source vs native)');
put('');
put('| Component | Files | Status | Provenance |');
put('|---|---|---|---|');
for (const phase of merge.phases) {
  const converted = phase.recordLedger.filter((record) => record.source !== 'native-2k26-273');
  const preserved = phase.recordLedger.filter((record) => record.source === 'native-2k26-273');
  for (const record of converted) {
    const provenance = phase.overlays.find((overlay) => record.source === overlay.component + '-overlay');
    put('| p' + phase.phase + ' `' + record.name + '` | record ' + record.index + ' of `' + phase.outputSha256.slice(0, 16) + '...` | **CONVERTED from 2K19-273 source** (' + record.source + ') | ' + (provenance ? provenance.provenance : record.componentProvenance) + ' |');
  }
  put('| p' + phase.phase + ' remaining records | ' + preserved.length + ' (`' + preserved.map((record) => record.name).join('`, `') + '`) | **native 2K26-273 placeholders** | ' + 'byte-identical beyond the re-keyed id; NOT converted content |');
}
const groups = new Map();
for (const member of intent.members) {
  if (member.role === 'clips-fixed') continue;
  const key = member.role;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(member);
}
for (const [role, members] of groups) {
  put('| ' + role + ' | ' + members.length + ' | ' + members[0].status + ' | ' + members[0].provenance + ' |');
}
put('| _textures.tdb | 1 | generated-empty-v6 | generated by the canonical bake (`' + build.tdb + '`) |');
put('');
if (verify.installed) {
  put('## Changed components versus the installed control snapshot');
  put('');
  put('Installed control: `' + verify.installed.archivePath + '` (key `' + verify.installed.archiveKey + '`, ' + verify.installed.archiveMembers + ' members).');
  put('Identical members: **' + verify.installed.identical + '**. Across both archives, only these members differ:');
  put('');
  for (const archive of verify.installed.different) put('- `' + archive + '`');
  for (const archive of verify.installed.notInCandidate) put('- `' + archive + '` (installed only, absent from candidate)');
  put('');
}
if (verify.wo005) {
  put('## Changed components versus the reviewed WO005 diagnostic');
  put('');
  put('WO005: `' + verify.wo005.archivePath + '` (key `' + verify.wo005.archiveKey + '`, ' + verify.wo005.archiveMembers + ' members).');
  put('Identical members: **' + verify.wo005.identical + '**. Different members:');
  put('');
  for (const archive of verify.wo005.different) put('- `' + archive + '` (converted body + converted facial bones)');
  for (const archive of verify.wo005.notInCandidate) put('- `' + archive + '` (WO005 only)');
  put('');
}
if (verify.reference) {
  put('## Discriminating diff versus the preceding candidate');
  put('');
  put('Reference: `' + verify.reference.archivePath + '` (key `' + verify.reference.archiveKey + '`, ' + verify.reference.archiveMembers + ' members).');
  put('Identical members: **' + verify.reference.identical + '**. Different members (must be only the five pair JSFBs):');
  put('');
  for (const archive of verify.reference.different) put('- `' + archive + '` (schema-aware vtable/uoffset relocation applied)');
  for (const archive of verify.reference.notInCandidate) put('- `' + archive + '` (reference only)');
  put('');
}
put('## Remaining native components (explicit)');
put('');
for (const phase of merge.phases) {
  const preserved = phase.recordLedger.filter((record) => record.source === 'native-2k26-273');
  put('- p' + phase.phase + ': ' + preserved.map((record) => '`' + record.name + '`').join(', ') + ' (' + preserved.length + ' native record(s); facial `base` bone, descriptors 48..767 and stream from 0x9C inside the converted facial record also remain native bit-exact)');
}
put('- Container-level scaffolding: five adefs (identity-transformed native), five pair tables (native base tokens), assembly 14002 (generated structural), 14001 closure, five shared registries, generated empty `_textures.tdb`.');
put('- Companion conversions (ring/object/aux/camera/event) are not present; native placeholder semantics remain.');
put('');
put('## ID/duration/link checks (independent of the builder)');
put('');
for (const check of verify.checks) {
  if (/clips-ids|duration|pair-|assembly|registry|eng-sdb|stale|untouched|overlay|tdb|key|extraction|member|hide|basename|diff-only|wo005/.test(check.name)) {
    put('- ' + (check.ok ? 'PASS' : 'FAIL') + ' `' + check.name + '`' + (check.detail ? ' :: ' + JSON.stringify(check.detail).slice(0, 220) : ''));
  }
}
put('');
put('## Resolved/unresolved dependency ledger');
put('');
put('- Resolved since the reviewed WO005 diagnostic: 4 remaining identity ADEF GUI reopens (110/120/130/140) pass in AnimationEditor (see `adefs-editor/remaining-phases-gui-reopen-verification.json`).');
put('- Resolved: source track-name hash for all 345 body+facial source identifiers (`.local/source19-name-hash-result.json`).');
put('- Integrated: facial bone performance (7 source channels -> 8-track native facial record) for all five phases; lead independent decoder 5/5 PASS, max rotation error 0.00035 deg (`haiku-273/facial-independent-check.json`).');
put('- Unfinished inside the facial record: `base` bone (no 2K19 counterpart) and the descriptors 48..767 / stream-from-0x9C morph area remain native bit-exact (explicitly unfinished).');
put('- Unresolved: original ring/object/aux/camera/event companion conversion (children 2273, 2730-2739 identified; roles partly unresolved).');
put('- Unresolved: runtime playback, editor reopen of the converted facial records, and visual acceptance. Offline checks never establish playback.');
put('');
put('## Owner test and rollback (only after Codex authorization)');
put('');
put('1. Test input: `' + build.cak + '` SHA256 `' + build.cakSha256 + '`.');
put('2. Install: copy it over the game slot `C:\\SteamLibrary\\steamapps\\common\\WWE 2K26\\mods\\aurora-2k25-replace-mod.cak` (outer manifest order and owner mods unchanged; keep the basename).');
put('3. Launch 2K26, select entrance test557 / DOLPH ZIGGLER 1, and attempt a full entrance.');
put('4. Expected if the linkage fix is correct: test557 loads and advances through all five phases (Intro, Stage, Ramp, RingIn, Ring).');
put('5. Failure interpretation: capture `DataCtrlLink.log` and the crash dump; the failure must be tied to this exact hash, not assigned the old cause by assumption. Success establishes runtime linkage only - not full source fidelity, because native placeholders remain.');
put('6. Rollback: copy `baseline-recovery\\installed-snapshot\\aurora-2k25-replace-mod.cak` (SHA256 `b644c39e2aba1d51fe40b72f514a568e841691fd2904bf578896db64e1a71d73`) back to the same slot; verify the hash after copying. No manifest edit is needed.');
put('');
put('## Next step (owner)');
put('');
put('None while offline lanes run. When Codex presents the candidate for the runtime step, one game observation decides only whether test557 loads and advances through the five phases; fidelity remains gated by the facial/companion lanes.');
put('');

const target = path.join(buildRoot, 'PROTOTYPE-READINESS.md');
fs.writeFileSync(target, lines.join('\n'), 'utf8');
console.log('readiness report written: ' + target);
